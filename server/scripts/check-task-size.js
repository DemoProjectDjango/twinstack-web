let exact = 0;
let critical = 0;
let soft = 0;
const failures = [];
for (const [instruction, expected, images = []] of CASES) {
  const result = taskSize({ instruction, images });
  const ok = result.size === expected;
  if (ok) exact++;
  else if ((expected === "complex" && result.size === "small") || (expected === "small" && result.size === "complex")) {
    critical++;
    failures.push(["CRITICAL", instruction, expected, result]);
  } else {
    soft++;
    failures.push(["soft", instruction, expected, result]);
  }
  if (verbose) console.log(`${ok ? "ok " : "XX "} ${result.size.padEnd(8)} ${String(result.score).padStart(2)}  ${instruction}\n      ${result.reasons.join(" | ")}`);
}

for (const [level, instruction, expected, r] of failures) {
  console.log(`${level.padEnd(8)} expected ${expected.padEnd(8)} got ${r.size.padEnd(8)} (${r.score})  ${instruction}\n         ${r.reasons.join(" | ")}`);
}
console.log(`\n${CASES.length} cases: ${exact} exact (${((exact / CASES.length) * 100).toFixed(1)}%), ${soft} one step off, ${critical} critical (small <-> complex)`);
if (critical) process.exitCode = 1;
