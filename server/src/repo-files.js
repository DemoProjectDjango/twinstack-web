import { existsSync } from "node:fs";
import fs from "node:fs/promises";
import path from "node:path";
import { rebaseCss, rebaseHtml } from "./original-pages.js";
import { createPageAt, getOverview, inside, saveHtmlSource } from "./site-files.js";
import { WorkspaceError, acquire, tryGit, workspaceDir } from "./workspace.js";

// The Files screen: the repo's folders, and uploading a file into one, in a new folder if the owner
// wants. Only assets/ and static/ take uploads: the build publishes those two (assets/ as it is,
// static/ at the site's root). The rest is listed, locked, with why: a file in scripts/ or content/
// would become code or a page, and a site update can replace what's under the template's folders.
// Git keeps no empty folders, so a new folder is the client's until a file is uploaded into it.

const MAX_FILE_BYTES = 10 * 1024 * 1024;
const MAX_LISTED = 5000;
const MAX_DEPTH = 10;
const MAX_NAME = 80;
const NAME = /^[A-Za-z0-9_](?:[A-Za-z0-9._-]*[A-Za-z0-9_-])?$/;

const HIDDEN = new Set([".git", "node_modules", "dist"]);
const TOOLS = "The site's own tools. A site update can replace what's here, so uploads aren't offered.";
const LOCKED = {
  content: "Your pages and business info. Change them on the Pages and Business info screens.",
  styles: "Your site's styling. Change it on the Custom code screen.",
  knowledge: "The AI's notes about your site. Change them on the AI notes screen.",
  scripts: TOOLS,
  templates: TOOLS,
  ".github": TOOLS,
  "assets/css": "Your site's styling, some of it generated by each build. Change it on the Custom code screen.",
  "assets/js": TOOLS,
  "static/assets": "Files here would replace the site's own assets. Use the assets folder instead.",
};
const NOT_PUBLISHED = "This folder isn't published with your site, so a file here couldn't be reached. Use assets or static.";
// What the build writes at the site's root, which a file in static/ would replace.
const BUILT_FILES = new Set(["index.html", "404.html", "sitemap.xml", "rss.xml", "search-index.json", "CNAME", "_redirects"]);

const isPublic = (rel) => rel === "assets" || rel === "static" || rel.startsWith("assets/") || rel.startsWith("static/");
const lockOf = (rel) => {
  const locked = Object.keys(LOCKED).find((folder) => rel === folder || rel.startsWith(`${folder}/`));
  if (locked) return LOCKED[locked];
  return isPublic(rel) ? null : NOT_PUBLISHED;
};
/** Where the published site serves a file: assets/ as it is, static/ at the root. */
const addressOf = (rel) => (rel.startsWith("static/") ? `/${rel.slice("static/".length)}` : `/${rel}`);

/** A file or folder name that's safe in a web address: "Price list (2026).pdf" → "Price-list-2026.pdf". */
export function cleanFileName(raw) {
  const name = String(raw ?? "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^A-Za-z0-9._-]+/g, "-")
    .replace(/-*\.-*/g, ".")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");
  // Shortened from the front, so the extension stays.
  return name.length > MAX_NAME ? name.slice(-MAX_NAME).replace(/^[-.]+/, "") : name;
}

/** A folder and what's in it. Links are never followed: one could point out of the repo. A locked folder's contents aren't listed. */
async function readFolder(dir, rel, budget, depth = 0) {
  const locked = lockOf(rel);
  const folder = { name: path.posix.basename(rel), path: rel, locked, files: [], folders: [] };
  if (locked) return folder;
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    if (entry.name.startsWith(".") || HIDDEN.has(entry.name) || budget.left <= 0) continue;
    budget.left--;
    const full = path.join(dir, entry.name);
    const child = `${rel}/${entry.name}`;
    if (entry.isDirectory() && depth < MAX_DEPTH) folder.folders.push(await readFolder(full, child, budget, depth + 1));
    else if (entry.isFile()) folder.files.push({ name: entry.name, size: (await fs.stat(full)).size, address: addressOf(child) });
  }
  return folder;
}

/** The repo's folders: assets and static first (static is listed even before it has a file), then the rest. */
export async function listRepoFiles(key) {
  const dir = workspaceDir(key);
  const budget = { left: MAX_LISTED };
  const names = (await fs.readdir(dir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && !HIDDEN.has(entry.name) && (!entry.name.startsWith(".") || LOCKED[entry.name]))
    .map((entry) => entry.name);
  const others = names.filter((name) => name !== "assets" && name !== "static").sort((a, b) => a.localeCompare(b));
  const folders = [];
  for (const name of ["assets", "static", ...others]) folders.push(await readFolder(path.join(dir, name), name, budget));
  return { folders, pages: await convertedPages(key), maxBytes: MAX_FILE_BYTES };
}

/** The same page however it's written: /about, /about/ and /about.html. */
const pageKey = (address) => address.toLowerCase().replace(/(^|\/)index\.html?$/, "$1").replace(/\.html?$/, "").replace(/\/+$/, "") || "/";

/** Why this file can't go here, when it would replace what the build makes. */
async function replacesBuilt(key, rel) {
  if (!rel.startsWith("static/")) return null;
  const inRoot = rel.slice("static/".length);
  if (BUILT_FILES.has(inRoot)) return `A file called ${inRoot} here would replace the one your site builds.`;
  const { collections } = await getOverview(key);
  const page = collections.flatMap((c) => c.pages).find((p) => p.address && pageKey(p.address) === pageKey(addressOf(rel)));
  return page ? `A file called ${inRoot} here would replace your "${page.title}" page. Rename the file, or put it in another folder.` : null;
}

/** Saves one file in a folder, making the folder if it's new. A file already there is only replaced when asked (409 otherwise). */
export async function uploadRepoFile(key, { folder, name, data, replace }) {
  const parts = typeof folder === "string" ? folder.split("/") : [];
  if (!parts.length || parts.length > MAX_DEPTH + 1 || parts.some((part) => part.length > MAX_NAME || !NAME.test(part))) {
    throw new WorkspaceError("Folder names can use letters, numbers, dots, dashes and underscores.", 400);
  }
  if (parts.some((part) => HIDDEN.has(part))) throw new WorkspaceError(`A folder can't be called ${parts.find((part) => HIDDEN.has(part))}: it's left out of what's saved.`, 400);
  const locked = lockOf(folder);
  if (locked) throw new WorkspaceError(locked, 403);
  const file = cleanFileName(name);
  if (!file) throw new WorkspaceError("That file has no usable name. Rename it, then try again.", 400);
  if (typeof data !== "string" || !data) throw new WorkspaceError(`${file} is empty.`, 400);
  const buffer = Buffer.from(data, "base64");
  if (!buffer.length) throw new WorkspaceError(`${file} is empty.`, 400);
  if (buffer.length > MAX_FILE_BYTES) throw new WorkspaceError(`${file} is over 10 MB. Files that large are better kept elsewhere and linked to.`, 400);
  const rel = `${folder}/${file}`;
  const built = await replacesBuilt(key, rel);
  if (built) throw new WorkspaceError(built, 400);

  const dir = workspaceDir(key);
  const target = inside(dir, rel);
  const release = acquire(key, `saving ${file}`);
  try {
    // A file the repo's .gitignore leaves out would seem saved, then never be published.
    if ((await tryGit(dir, ["check-ignore", "--quiet", "--", rel])) !== null) throw new WorkspaceError(`Files like ${file} are left out of what's published. Rename it, then try again.`, 400);
    for (let at = 1; at <= parts.length; at++) {
      const stat = await fs.lstat(inside(dir, parts.slice(0, at).join("/"))).catch(() => null);
      if (stat && !stat.isDirectory()) throw new WorkspaceError(`${parts.slice(0, at).join("/")} is a file, not a folder.`, 400);
    }
    const existing = await fs.lstat(target).catch(() => null);
    if (existing && !existing.isFile()) throw new WorkspaceError(`There's already a folder called ${file} here.`, 400);
    if (existing && replace !== true) throw new WorkspaceError(`There's already a file called ${file} in this folder.`, 409);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, buffer);
    return { file: rel, name: file, address: addressOf(rel), replaced: Boolean(existing) };
  } finally {
    release();
  }
}

const LOCAL_REFERENCE = /\b(?:src|href|poster|data-src)\s*=\s*["']([^"']+)["']|url\(\s*["']?([^"')]+)["']?\s*\)/gi;

/** Where the page (at `file`) and its stylesheets look for each of `names`, as the folders to save them in. */
function assetFolders(names, file, html, css) {
  const found = new Map();
  for (const [from, text] of [[file, html], ...css.map((sheet) => [sheet.rel, sheet.content])]) {
    for (const match of text.matchAll(LOCAL_REFERENCE)) {
      const href = (match[1] ?? match[2]).trim().replace(/[?#].*$/, "");
      if (!href || /^[a-z][a-z0-9+.-]*:|^\/\//i.test(href)) continue;
      const rel = path.posix.normalize(href.startsWith("/") ? href.slice(1) : path.posix.join(path.posix.dirname(from), href));
      const name = path.posix.basename(rel);
      if (rel.startsWith("..") || !names.includes(name) || found.has(name)) continue;
      const folder = path.posix.dirname(rel);
      // The page asks for it at this address, so it goes where the build publishes that address.
      found.set(name, /^(assets|static)(\/|$)/.test(folder) ? folder : folder === "." ? "static" : `static/${folder}`);
    }
  }
  return [...found].map(([name, folder]) => ({ name, folder }));
}

/**
 * Gets an uploaded HTML file ready for `page-convert`, as `prepareOriginalPage` does for one in the
 * repo: saves it and the stylesheets and scripts that came with it, and makes the content page at the
 * address its name gives (index.html is the homepage). A page already there is only taken over when
 * asked (409 otherwise). `assets` are the other files that came with it: the client uploads each to
 * the folder returned, so the page finds it. Returns the command's input, and whether the page is new.
 */
export async function prepareUploadedPage(key, { name, content, css = [], js = [], assets = [], replace }) {
  const base = cleanFileName(String(name ?? "").replace(/\.html?$/i, "")).toLowerCase();
  if (!base) throw new WorkspaceError("That file has no usable name. Rename it, then try again.", 400);
  if (typeof content !== "string") throw new WorkspaceError("No HTML received.", 400);
  const file = `${base}.html`;
  const address = base === "index" ? "/" : `/${file}`;
  const dir = workspaceDir(key);
  // The build copies static/ over the pages, so a plain file with this name would hide the page.
  if (base !== "index" && existsSync(inside(dir, `static/${file}`))) throw new WorkspaceError(`There's a plain file called ${file} in the static folder, which would hide this page. Rename one of them.`, 400);
  const { collections } = await getOverview(key);
  const existing = collections.flatMap((c) => c.pages).find((p) => p.address && pageKey(p.address) === pageKey(address));
  if (existing && replace !== true) throw new WorkspaceError(`Your "${existing.title}" page is already at ${address}. This would replace it.`, 409);

  const linkedAs = (sheetName) => {
    const link = [...content.matchAll(/<link\b[^>]*\bhref\s*=\s*["']([^"'?#]+)/gi)].map((m) => m[1]).find((href) => path.posix.basename(href) === sheetName);
    return link && !/^[a-z][a-z0-9+.-]*:|^\/\//i.test(link) ? path.posix.normalize(link.replace(/^\//, "")) : `css/${sheetName}`;
  };
  const sheets = (Array.isArray(css) ? css : []).filter((s) => typeof s?.content === "string").map((s) => ({ name: path.posix.basename(String(s.name)), rel: linkedAs(path.posix.basename(String(s.name))), content: s.content }));
  const saved = await saveHtmlSource(key, {
    name: base,
    content: rebaseHtml(content, file, (rel) => existsSync(inside(dir, rel)) || existsSync(inside(dir, `static/${rel}`))),
    css: sheets.map((s) => ({ name: s.name, content: rebaseCss(s.content, s.rel) })),
    js,
  });
  const title = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(content)?.[1].replace(/\s+/g, " ").trim().slice(0, 100);
  const page = existing?.file ?? (await createPageAt(key, { url: address, title: /[<>&]/.test(title ?? "") ? undefined : title || undefined })).file;
  return {
    page,
    source: saved.source,
    css: saved.css.map((c) => c.source),
    js: (saved.js ?? []).map((c) => c.source),
    address,
    created: !existing,
    assets: assetFolders((Array.isArray(assets) ? assets : []).map(cleanFileName), file, content, sheets),
  };
}

