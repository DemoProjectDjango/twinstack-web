const CONVERTED_STYLESHEET = /^stylesheet:\s*["']?\/(assets\/css\/imported\/([a-z0-9-]+)\.css)["']?\s*$/m;

/** The stylesheet that marks a page as made from an HTML file, read from its frontmatter. */
async function convertedStylesheet(dir, file) {
  const text = await fs.readFile(inside(dir, file), "utf8").catch(() => "");
  return CONVERTED_STYLESHEET.exec(/^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? "");
}

/** The pages made from an HTML file: they have no file in a folder, so the Files screen lists them apart. */
async function convertedPages(key) {
  const dir = workspaceDir(key);
  const { collections } = await getOverview(key);
  const pages = [];
  for (const page of collections.flatMap((c) => c.pages)) {
    if (await convertedStylesheet(dir, page.file)) pages.push({ file: page.file, title: page.title, address: page.address, home: page.address === "/" });
  }
  return pages;
}

/** Every file that could use an address, and how to name it to the owner. */
async function usageSources(key) {
  const dir = workspaceDir(key);
  const { collections } = await getOverview(key);
  const titles = new Map(collections.flatMap((c) => c.pages).map((p) => [p.file, p.title]));
  const sources = [...titles].map(([file, title]) => ({ file, label: `the "${title}" page` }));
  const add = (file, label) => sources.push({ file, label });
  add("site.config.json", "your logo or site details");
  add("templates/partials/header.html", "your header");
  add("templates/partials/footer.html", "your footer");
  for (const [name, label] of [["navigation.json", "your menu or footer"], ["scripts.json", "your scripts"]]) add(`content/data/${name}`, label);
  for (const entry of await fs.readdir(inside(dir, "assets/css/imported")).catch(() => [])) {
    const owner = [...titles].find(([file]) => path.posix.basename(file, ".md").toLowerCase() === entry.replace(/\.css$/, ""));
    if (entry.endsWith(".css")) add(`assets/css/imported/${entry}`, owner ? `the "${owner[1]}" page` : "a page's styling");
  }
  return sources;
}

/**
 * What still uses this address, in words, so the owner is told before removing it: a link or image
 * pointing at a missing file is an error in the site's check, which stops the site being published.
 * `except` is the page being removed, with its own stylesheet.
 */
export async function fileUsage(key, address, except = null) {
  if (typeof address !== "string" || !address.startsWith("/") || address === "/") return [];
  const escaped = address.slice(1).replace(/\.html?$/i, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const ending = /\.html?$/i.test(address) ? "(?:\\.html?)?" : "";
  const uses = new RegExp(`(?:^|[/"'(=\\s])${escaped}${ending}(?:$|[?#"')\\s])`, "m");
  const dir = workspaceDir(key);
  const found = new Set();
  const own = except ? (await convertedStylesheet(dir, except))?.[1] : null;
  for (const { file, label } of await usageSources(key)) {
    if (file === except || file === own) continue;
    const text = await fs.readFile(inside(dir, file), "utf8").catch(() => "");
    if (uses.test(text)) found.add(label);
  }
  return [...found].slice(0, 8);
}

/** Removes a file from assets/ or static/, and any folder that leaves empty (git keeps no empty folders). */
export async function removeRepoFile(key, file) {
  const parts = typeof file === "string" ? file.split("/") : [];
  if (parts.length < 2 || parts.some((part) => !part || part === "." || part === ".." || part.startsWith(".") || HIDDEN.has(part))) throw new WorkspaceError("That isn't a file you can remove here.", 400);
  const folder = parts.slice(0, -1).join("/");
  const locked = lockOf(folder);
  if (locked) throw new WorkspaceError(locked, 403);
  const dir = workspaceDir(key);
  const release = acquire(key, `removing ${parts.at(-1)}`);
  try {
    for (let at = 1; at <= parts.length; at++) {
      const stat = await fs.lstat(inside(dir, parts.slice(0, at).join("/"))).catch(() => null);
      if (!stat) throw new WorkspaceError(`${parts.at(-1)} isn't there any more.`, 404);
      if (at < parts.length ? !stat.isDirectory() : !stat.isFile()) throw new WorkspaceError("That isn't a file you can remove here.", 400);
    }
    await fs.unlink(inside(dir, file));
    for (let at = parts.length - 1; at > 1; at--) {
      const empty = await fs.rmdir(inside(dir, parts.slice(0, at).join("/"))).then(() => true, () => false);
      if (!empty) break;
    }
  } finally {
    release();
  }
}

/** Removes a page made from an HTML file: the page, so it's gone from Pages, with its stylesheet and scripts. Images stay: others may use them. */
export async function removeConvertedPage(key, file) {
  const dir = workspaceDir(key);
  const page = (await convertedPages(key)).find((p) => p.file === file);
  if (!page) throw new WorkspaceError("That isn't a page made from an HTML file.", 404);
  if (page.home) throw new WorkspaceError("Your homepage can't be removed: visitors see it first at your address. Upload a new index.html to replace it.", 400);
  const sheet = await convertedStylesheet(dir, file);
  const release = acquire(key, `removing ${page.title}`);
  try {
    await fs.rm(inside(dir, file));
    await fs.rm(inside(dir, sheet[1]), { force: true });
    await fs.rm(inside(dir, `assets/js/imported/${sheet[2]}`), { recursive: true, force: true });
  } finally {
    release();
  }
}
